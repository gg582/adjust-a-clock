"""Report languages: per-language string tables and the process-wide current language.

Table keys are the Korean source strings. Korean is the identity mapping, so ko output
is byte-identical to the pre-i18n behavior. Templates use str.format placeholders and
each row must have exactly one entry per language. Machine-readable output (요약.json)
is rendered under use_lang('ko') so it never changes.
"""
from contextlib import contextmanager

LANGUAGES = ('ko', 'en', 'ru', 'de', 'fr')

_lang = 'ko'


def set_lang(lang):
    global _lang
    if lang not in LANGUAGES:
        raise ValueError(f'unknown language: {lang}')
    _lang = lang


def get_lang():
    return _lang


@contextmanager
def use_lang(lang):
    """Temporarily switch the report language (used to keep 요약.json in Korean)."""
    prev = get_lang()
    set_lang(lang)
    try:
        yield
    finally:
        set_lang(prev)


def tr(key, **kw):
    """Translate a Korean source string into the current language and fill placeholders."""
    s = key if _lang == 'ko' else _TABLES[_lang].get(key, key)
    return s.format(**kw) if kw else s


